#include<stdio.h>
int main(void)
{
	const double GRAVITY = 9.80; // g = 9.80 m/s^2 
        const double EFFICIENCY = 0.90; // 90% efficiency constant
	const double WATER_DENSITY = 1000.0; // the mass of 1 cubic meter of water = 1000kg
	const double WATTS_TO_MEGAWATTS = 1000000.0; // conversion factor for Watts to Megawatts
	double height, flow_rate;
	double mass_per_second, work_done, power_watts, power_megawatts;
	printf("Enter the height of the dam(in meters): ");
	scanf("%lf", &height);
	printf("Enter the flow rate of water(in cubic meters per second): ");
	scanf("%lf", &flow_rate);

	mass_per_second = WATER_DENSITY * flow_rate;
	work_done = mass_per_second * GRAVITY * height;
	power_watts = EFFICIENCY * work_done;
	power_megawatts = power_watts / 1000000.0;
	
	printf("predicted power generated by the hydroelectric dam: %.2f megawatts\n", power_megawatts);
	return 0;
}





